#ifdef NDEBUG
#undef NDEBUG
#endif
#include "mycelia.hpp"
#include <cassert>
#include <cmath>
#include <iomanip>
#include <iostream>
#include <sstream>
using namespace mycelia;
static bool near(double a,double b) {return std::abs(a-b)<1e-12;}
static Pattern make(int id) {
    Pattern p;
    std::ostringstream signature,hash;
    signature << std::hex << std::setw(64) << std::setfill('0') << id;
    hash << std::hex << std::setw(64) << std::setfill('0') << (id+16);
    p.signature=signature.str();p.energy_hash=hash.str();
    p.energy_mean=.2+(id-1)*.2;p.pheromone_mean=.1;p.nutrient_mean=.2;
    p.mood_vector={.1*(id-1),.5,.7};p.stability=.4+(id-1)*.1;
    return p;
}
int main() {
    DynamicAssociativeDatabase db;
    auto empty=db.associative_query("none");
    assert(empty.empty()&&db.last_query()->returned==0);
    for(int i=1;i<=3;++i)db.store_pattern(make(i));
    // Original Python with no history -> 1x1 grid.
    auto initial=db.associative_query("hello",1.2);
    assert(initial.size()==3&&near(initial[0].x,1.0)&&near(initial[0].y,1.0));
    // Make history via real observation, then seed a fresh DB by an observation followed by replacements.
    DynamicAssociativeDatabase observed;
    WorldFields fields{{0,1,2,3},{.2,.4},{.5,.7}};
    auto obs=ObserverNetwork::encode(fields.pheromone,fields.nutrient);
    observed.observe(fields,obs,.3,.3,.8);
    auto agents=observed.associative_query("hello",1.2);
    assert(agents.size()==1);
    // Golden values generated by actually running the original Python observe + associative_query.
    assert(near(agents[0].x,0.475));
    assert(near(agents[0].y,0.4782608695652174));
    assert(near(agents[0].energy,0.9));
    assert(near(agents[0].coupling,1.0121573483785817));
    assert(observed.last_query()->returned==3);
    assert(observed.last_query()->signatures[0]==
        "7565f18b38fa28b85e48d1ed5b14c59298b1a6bf392910a96792cf8c1aab26cd");
    auto single=db.associative_query("KR Compiler",.2);
    assert(single.size()==1);
    assert(near(single[0].energy,.12));
    assert(near(single[0].coupling,.77775));
    assert(db.last_query()->signatures.size()==1);
    db.delete_pattern(make(3).signature);
    assert(db.attractor_count()==2);
    db.clear();
    assert(db.attractor_count()==0&&!db.last_query().has_value());
    std::cout << "PASS: associative_query, Python MT, zero history, ranking, intensity, last query\n";
}
